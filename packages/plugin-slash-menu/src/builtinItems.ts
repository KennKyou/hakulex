function $setBlocks(create: () => ElementNode) {
  const selection = $getSelection()
  if ($isRangeSelection(selection))
    $setBlocksType(selection, create)
}

function heading(tag: HeadingTagType, level: number, icon: SlashMenuItem['icon']): SlashMenuItem {
  return {
    key: tag,
    title: `標題 ${level}`,
    description: ['大標題', '章節標題', '小節標題'][level - 1],
    keywords: [
      'heading',
      `heading${level}`,
      'title',
      'biaoti',
    ],
    group: '基本',
    icon,
    run: () => $setBlocks(() => $createHeadingNode(tag)),
  }
}

