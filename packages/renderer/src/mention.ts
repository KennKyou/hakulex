export interface MentionProps {
  platform?: unknown
  handle?: unknown
  displayName?: unknown
}

function asText(value: unknown) {
  return typeof value === 'string'
    ? value
    : ''
}

/** What a mention shows as its name, without the `@`. */
export function mentionLabel(props: MentionProps): string {
  return asText(props.displayName) || asText(props.handle).replace(/^@+/, '')
}

/**
 * Where a mention goes, or `null` for plain text. The platform comes from a document, so it can
 * be `__proto__`, and `.` and `..` would be resolved away instead of naming an account.
 */
export function mentionUrl(props: MentionProps): string | null {
  const platform = asText(props.platform)
  const handle = asText(props.handle).replace(/^@+/, '')
  if (!handle || handle === '.' || handle === '..' || !Object.hasOwn(MENTION_PLATFORMS, platform))
    return null
  return MENTION_PLATFORMS[platform].url(handle)
}

export function renderMention(props: MentionProps): VNode {
  const url = mentionUrl(props)
  const label = mentionLabel(props)
  if (!url) {
    return h('span', { class: `${contentTheme.mention} hlx-mention--plain` }, [
      h('span', { class: 'hlx-mention-handle' }, `@${label}`),
    ])
  }
  const platform = MENTION_PLATFORMS[props.platform as string]
  return h('span', { class: contentTheme.mention }, [
    h('span', { 'class': 'hlx-mention-icon', 'aria-hidden': 'true' }, [
      h('svg', {
        viewBox: '0 0 24 24',
        width: '1em',
        height: '1em',
        fill: platform.color ?? 'currentColor',
      }, [
        h('path', { d: platform.icon }),
      ]),
    ]),
    h('a', {
      class: 'hlx-mention-handle',
      href: url,
      rel: 'noopener noreferrer',
      target: '_blank',
    }, label),
  ])
}

export const MentionView: FunctionalComponent<MentionProps> = props => renderMention(props)
MentionView.props = ['platform', 'handle', 'displayName']
